'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const flow=require('../lib/automation-flow.cjs');
const four=flow.SYSTEMS;
assert.deepEqual(flow.parseSelection('1',four,false),['Futura100']);
assert.deepEqual(flow.parseSelection('2',four,false),['Talento100']);
assert.deepEqual(flow.parseSelection('1,2',four,true),['Futura100','Talento100']);
assert.deepEqual(flow.parseSelection('Futura100 y Talento100',four,true),['Futura100','Talento100']);
assert.deepEqual(flow.parseSelection('Consulta TI',four,false),['Consulta TI']);
assert.equal(flow.parseSelection('1,2',four,false),null,'No habilitar selección múltiple sin permiso');
assert.equal(flow.parseSelection('5',four,true),null);
assert.equal(flow.parseSelection('Futura100',four.slice(1),false),null,'Sistema deshabilitado');
assert.deepEqual(flow.parseSelection('1',four.slice(1),false),['Talento100'],'Numeración dinámica');
assert.deepEqual(flow.firstRequest('Futura100, Talento100: No carga el módulo de reportes',four,true),{systems:['Futura100','Talento100'],issue:'No carga el módulo de reportes'});
assert.equal(flow.firstRequest('Futura100: x',four,true),null,'El inconveniente debe tener 2 caracteres');
assert.equal(flow.firstRequest('hola',four,true),null);
assert.equal(flow.keyword('menú'),true);
assert.equal(flow.keyword('hola'),false);
assert.deepEqual(flow.availableSystems('invalid json'),four);
assert.match(flow.menuText(four,true),/1,2/);
const code=fs.readFileSync(path.join(root,'lib/automation.ts'),'utf8');
assert.match(code,/if\(activeTicket\)return null;/,'Bloqueo de ticket abierto');
assert.match(code,/ev\.isGroup\|\|ev\.message\.phone\.endsWith\('@g\.us'\)\|\|ev\.outbound/,'Excluir grupos y mensajes salientes');
assert.match(code,/hasRecentManualOutreach/,'Intervención humana');
assert.match(code,/session\?\.account_id!==\(msg\.account_id\|\|''\)/,'Aislamiento por cuenta');
assert.match(code,/policy\(s\)\.confirmation\?summary\(s\):createTicket\(s,lastId\)/,'Confirmación opcional');
assert.match(code,/if\(policy\(session\)\.shortForm\)return finishShortRequest/,'Modo corto');
assert.match(code,/function createTicket\(/,'Protección anti duplicados de Jira');
console.log('[OK] 23 comprobaciones: elección simple/múltiple, sistemas, primer mensaje, bloqueo de ticket abierto, intervención humana y modos de confirmación.');
