'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const support=read('app/components/SupportAutomationSettings.tsx');
const control=read('app/components/AutomationControlCenter.tsx');
const contacts=read('app/components/GuardiaContacts.tsx');
assert.match(support,/setEnabled/,'Interruptor del asistente persistente');
assert.match(support,/>Equipo de soporte</,'Solo una sección visible de equipo');
assert.match(support,/roles\.map/,'Tres roles de Jira');
assert.match(support,/GuardiaContacts role=\{role\}/,'Contactos WhatsApp en cada tarjeta');
assert.match(control,/Horarios de atención/);
for(const label of ['Horario laboral','Fuera de horario','Fines de semana','Feriados','Clientes sin automatización'])assert.ok(control.includes(label),'Falta '+label);
assert.match(control,/\/api\/automation\/control/,'Persistencia de horarios');
assert.match(control,/\/api\/automation\/people/,'Persistencia de exclusiones');
assert.doesNotMatch(control,/twControlTabs|tab==='Historial'|Niveles y estados de Jira/,'No deben volver las pestañas duplicadas');
for(const label of ['Activo','Avisos','Seguimiento','Quitar'])assert.ok(contacts.includes(label),'Falta control '+label);
assert.match(read('app/api/settings/route.ts'),/export async function PATCH/);
assert.match(support,/no son botones reales/,'No confundir simulador con lista interactiva real');
console.log('[OK] Equipo de soporte unificado, horarios, exclusiones, contactos y simulador bien diferenciados');
