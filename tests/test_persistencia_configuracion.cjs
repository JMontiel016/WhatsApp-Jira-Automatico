'use strict';
// Static contract + database roundtrip smoke test. No access to production data.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const panel=read('app/components/SupportAutomationSettings.tsx');
const hours=read('app/components/AutomationControlCenter.tsx');
const api=read('app/api/settings/route.ts');
assert.match(panel,/assertSavedSettings\(stored,snapshot\)/,'Verificar lectura posterior al guardado');
assert.match(panel,/draftRevision\.current===revision/,'Preservar cambios posteriores al guardado');
assert.match(panel,/PATCH[\s\S]*automationEnabled/,'Interruptor principal independiente');
assert.match(panel,/setDirty\(false\)/,'Marcar datos guardados');
assert.doesNotMatch(panel,/defaultOpen=/,'No usar atributo React no válido');
assert.match(hours,/const confirmed=await api<Timing>\('\/api\/automation\/control'\)/);
assert.match(hours,/setDirtyTiming\(false\)/);
for(const token of ['automation_flow_start','automation_flow_short','automation_flow_confirm','automation_flow_multi','automation_flow_human','automation_flow_systems','automation_prompt_enabled_','automation_notice_']) assert.ok(api.includes(token),token);
assert.match(api,/export async function PATCH/);
const {DatabaseSync}=require('node:sqlite');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE settings(name TEXT PRIMARY KEY, value TEXT NOT NULL)');
const upsert=db.prepare('INSERT INTO settings(name,value) VALUES (?,?) ON CONFLICT(name) DO UPDATE SET value=excluded.value');
const flags={automation_enabled:'1',automation_flow_short:'1',automation_flow_confirm:'0',automation_flow_human:'1',automation_flow_multi:'1',automation_flow_start:'first',automation_allow_inside:'1',automation_allow_outside:'0',automation_allow_weekends:'1',automation_allow_holidays:'0',automation_prompt_enabled_ruc:'0'};
for(const [key,value] of Object.entries(flags))upsert.run(key,value);
let rows=Object.fromEntries(db.prepare('SELECT name,value FROM settings').all().map(x=>[x.name,x.value]));
assert.deepEqual(rows,flags);
for(const [key,value] of Object.entries(flags))upsert.run(key,value==='1'?'0':'1');
rows=Object.fromEntries(db.prepare('SELECT name,value FROM settings').all().map(x=>[x.name,x.value]));
assert.equal(rows.automation_enabled,'0');
assert.equal(rows.automation_flow_short,'0');
assert.equal(rows.automation_allow_inside,'0');
db.close();
console.log('[OK] Contratos de pantalla y API: guardado, lectura, estado del bot y horarios');
console.log('[OK] SQLite simulado: cambios activado/desactivado conservados');
console.log('[NOTA] Falta probar la interfaz con la base real de tu Ubuntu.');
