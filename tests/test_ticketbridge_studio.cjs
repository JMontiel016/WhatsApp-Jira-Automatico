'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=x=>fs.readFileSync(path.join(root,x),'utf8');
const ts=require('typescript');
for(const file of ['app/api/whatsapp/pairing-qr/route.ts','app/api/whatsapp/status/route.ts','app/api/settings/route.ts','app/components/WhatsAppConnectionPanel.tsx','app/components/SupportAutomationSettings.tsx','app/components/AutomationControlCenter.tsx','app/page.tsx','lib/automation.ts','lib/automation-extra-fields.ts']){
 const r=ts.transpileModule(read(file),{fileName:file,reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}});
 assert.equal((r.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error).length,0,'TSX syntax '+file);
}
const output=ts.transpileModule(read('lib/automation-extra-fields.ts'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};
vm.runInNewContext(output,{module:mod,exports:mod.exports,JSON,Object,String,Array,Boolean,RegExp});
const {parseExtraFields}=mod.exports;
const f={id:'f_abcdef',system:'Futura100',label:'Sucursal',required:true,enabled:true};
assert.equal(parseExtraFields(JSON.stringify([f])).length,1);
assert.equal(parseExtraFields(JSON.stringify([{...f,label:'x'}])).length,0);
assert.equal(parseExtraFields('invalid').length,0);
assert.equal(parseExtraFields(JSON.stringify([{...f,system:'Hack'}])).length,0);
const automation=read('lib/automation.ts');
assert.match(automation,/function validRuc\(value:string\)\{return value\.trim\(\)\.length>=2&&value\.trim\(\)\.length<=500/);
assert.match(automation,/case 'extra'/);
assert.match(automation,/fields_json/);
assert.match(automation,/\['1','SI','SÍ','CONFIRMAR'/);
assert.match(automation,/ev\.isGroup\|\|ev\.message\.phone\.endsWith\('@g\.us'\)/);
const route=read('app/api/whatsapp/pairing-qr/route.ts');
assert.match(route,/phase:result\.phase\|\|'waiting'/);
assert.match(route,/error:result\.error\|\|null/);
const connector=read('whatsapp/connector.cjs');
assert.match(connector,/protocolTimeout: 240000/);
assert.match(connector,/qrMaxRetries: 0/);
assert.match(connector,/restartWhatsApp/);
assert.match(connector,/BROWSER_STARTUP_WARNING_MS = 90000/);
assert.equal(read('lib/whatsapp-version.ts').includes('ticketbridge-sync-v6.7-sync'),connector.includes('ticketbridge-sync-v6.7-sync'));
assert.match(read('app/components/SupportAutomationSettings.tsx'),/Campos adicionales del formulario/);
assert.match(read('app/components/WhatsAppConnectionPanel.tsx'),/Diagnóstico de conexión/);
console.log('[OK] Sintaxis TS/TSX, QR, versión, grupos, confirmación, campos opcionales y diseño verificados.');
console.log('[NOTA] No reemplaza npm run build ni prueba real de WhatsApp/Jira.');
